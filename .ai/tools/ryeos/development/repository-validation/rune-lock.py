"""Agreement between the two Cargo locks.

The browser renderer (crates/clients/rune) is its own Cargo workspace so the
root lock, which the release chain vendors, names crates.io sources only. The
renderer still compiles the shared client crates, so every package both locks
resolve must resolve the same way.

A package is identified by (name, source, semver-compatible range): one lock
holds at most one version per range. For every such identity present in both
locks, the version and checksum must be equal. Identities present in only one
lock are exempt (the renderer's git sources and graphics stack, or root-only
crates the renderer never reaches).

--check       compare the locks (no cargo, no network); exit 1 on disagreement
--regenerate  rebuild the renderer lock from the root lock: seed it with every
              root package plus the renderer's own packages for ranges the
              root lock does not hold, let cargo prune and resolve it, then
              run the check. Shared packages therefore keep the root versions.

Usage: rune-lock.py (--check | --regenerate) [--project-path DIR]
"""

import argparse
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT_LOCK = "Cargo.lock"
RUNE_MANIFEST = "crates/clients/rune/Cargo.toml"
RUNE_LOCK = "crates/clients/rune/Cargo.lock"


def compatible_range(version):
    """Cargo's semver compatibility: the major, or 0.minor, or 0.0.patch."""
    major, minor, patch = version.split("+")[0].split("-")[0].split(".")
    if major != "0":
        return major
    return f"0.{minor}" if minor != "0" else f"0.0.{patch}"


def packages(path):
    return tomllib.loads(path.read_text())["package"]


def identity(package):
    return (package["name"], package.get("source"), compatible_range(package["version"]))


def resolved(path):
    found = {}
    for package in packages(path):
        key = identity(package)
        if key in found:
            raise ValueError(f"{path}: two versions in one compatible range: {key}")
        found[key] = (package["version"], package.get("checksum"))
    return found


def check(root):
    core, rune = resolved(root / ROOT_LOCK), resolved(root / RUNE_LOCK)
    failures = []
    for key in sorted(core.keys() & rune.keys(), key=lambda k: (k[0], k[2], k[1] or "")):
        if core[key] != rune[key]:
            name, source, _ = key
            failures.append(
                f"{name} ({source or 'path'}): root lock {core[key][0]}, renderer lock {rune[key][0]}"
                + ("" if core[key][0] != rune[key][0] else " (checksum differs)"))
    return failures, len(core.keys() & rune.keys())


def toml_value(value):
    if isinstance(value, list):
        if not value:
            return "[]"
        return "[\n" + "".join(f" {toml_value(item)},\n" for item in value) + "]"
    escaped = str(value).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def write_lock(path, version, entries):
    lines = ["# This file is automatically @generated by Cargo.",
             "# It is not intended for manual editing.",
             f"version = {version}", ""]
    for package in entries:
        lines.append("[[package]]")
        for field in ("name", "version", "source", "checksum", "dependencies"):
            if field in package:
                lines.append(f"{field} = {toml_value(package[field])}")
        lines.append("")
    path.write_text("\n".join(lines))


def regenerate(root):
    core_doc = tomllib.loads((root / ROOT_LOCK).read_text())
    rune_path = root / RUNE_LOCK
    core = core_doc["package"]
    seen = {identity(package) for package in core}
    own = [package for package in packages(rune_path) if identity(package) not in seen] \
        if rune_path.exists() else []
    seed = sorted(core + own, key=lambda p: (p["name"], p["version"], p.get("source", "")))
    write_lock(rune_path, core_doc["version"], seed)
    result = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--manifest-path", RUNE_MANIFEST],
        cwd=root, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, text=True)
    if result.returncode != 0:
        print(result.stderr, file=sys.stderr)
        return False
    return True


def main():
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--regenerate", action="store_true")
    parser.add_argument("--project-path", type=Path, default=Path.cwd())
    args = parser.parse_args()
    if args.regenerate and not regenerate(args.project_path):
        return 2
    failures, shared = check(args.project_path)
    for line in failures:
        print("rune lock: " + line, file=sys.stderr)
    if failures:
        print("rune lock: run rune-lock.py --regenerate to rebuild the renderer lock from the root lock",
              file=sys.stderr)
        return 1
    print(f"rune lock: ok ({shared} shared packages agree)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
