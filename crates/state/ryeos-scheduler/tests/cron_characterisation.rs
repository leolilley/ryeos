//! Characterisation of cron scheduling behaviour.
//!
//! These tests pin what the scheduler does for cron expressions through its
//! public entry points: `validate_expression`, `validate_timezone`,
//! `crontab::compute_next_fire` (next fire after an instant),
//! `crontab::nth_cron_boundary_after` (iteration of successive fires) and
//! `crontab::compute_scheduled_at` (most recent fire at or before now).
//!
//! The rule they enforce: no schedule that is valid today may fire at a
//! different time. Expected values were observed from the `cron` 0.16 and
//! `chrono-tz` implementation and are pinned exactly. Instants are RFC 3339
//! UTC strings; `ERR` is a refusal, `NONE` is "no fire exists".
//!
//! Pinned behaviours worth knowing:
//! - six fields, `sec min hour dom mon dow`; five fields are refused
//! - weekdays are 1 = Sunday .. 7 = Saturday; 0 is refused
//! - day-of-month and day-of-week combine with AND
//! - a wall-clock time inside a spring-forward gap is skipped
//! - a repeated fall-back time fires twice when fires are iterated, but a
//!   single `compute_next_fire` after the first occurrence jumps past the
//!   second (it walks wall-clock time from the given instant)
//! - the year range is 1970..=2100, so nothing fires after 2100

use ryeos_effect_contract::rfc3339::{format_unix_millis, parse_unix_millis};
use ryeos_scheduler::crontab::{compute_next_fire, compute_scheduled_at, nth_cron_boundary_after};
use ryeos_scheduler_contract::{validate_expression, validate_timezone};

fn ms(s: &str) -> i64 {
    parse_unix_millis(s).unwrap_or_else(|e| panic!("bad instant {s:?}: {e:?}"))
}

fn fmt(v: i64) -> String {
    format_unix_millis(v).unwrap()
}

fn show(r: Option<i64>) -> String {
    r.map_or_else(|| "NONE".to_owned(), fmt)
}

fn next_fire(expr: &str, tz: &str, after: &str) -> String {
    match compute_next_fire("cron", expr, tz, ms(after), None) {
        Err(_) => "ERR".to_owned(),
        Ok(v) => show(v),
    }
}

fn chain(expr: &str, tz: &str, start: &str, n: u32) -> String {
    (1..=n)
        .map(|i| show(nth_cron_boundary_after(expr, tz, ms(start), i)))
        .collect::<Vec<_>>()
        .join(" ")
}

fn recent(expr: &str, tz: &str, last: &str, now: &str) -> String {
    show(compute_scheduled_at(
        "cron",
        expr,
        tz,
        ms(now),
        Some(ms(last)),
        None,
    ))
}

fn accepts(expr: &str) -> &'static str {
    let validated = validate_expression("cron", expr).is_ok();
    let computed = compute_next_fire("cron", expr, "UTC", ms("2026-03-04T10:20:30Z"), None).is_ok();
    match (validated, computed) {
        (true, true) => "ok",
        (false, false) => "refused",
        _ => "SPLIT",
    }
}

fn zone(tz: &str) -> &'static str {
    let validated = validate_timezone(tz).is_ok();
    let computed =
        compute_next_fire("cron", "0 0 4 * * *", tz, ms("2026-03-04T10:20:30Z"), None).is_ok();
    match (validated, computed) {
        (true, true) => "ok",
        (false, false) => "refused",
        _ => "SPLIT",
    }
}

/// Compare every row; on any mismatch fail with one `PIN table#row|actual`
/// line per mismatch.
fn check<const N: usize>(
    table: &str,
    rows: &[([&str; N], &str)],
    actual: impl Fn(&[&str; N]) -> String,
) {
    let mut bad = Vec::new();
    for (idx, (inputs, expected)) in rows.iter().enumerate() {
        let got = actual(inputs);
        if got != *expected {
            bad.push(format!("PIN {table}#{idx}|{got}"));
        }
    }
    assert!(bad.is_empty(), "\n{}\n", bad.join("\n"));
}

