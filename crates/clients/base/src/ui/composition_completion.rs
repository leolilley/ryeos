//! Exact local composition receipt, not an executable admission response.
//!
//! A receipt is accepted only after the existing seat owner recomputes its
//! deterministic delta against the original preparation and causal history.
//! Its coordinates never grant authority or advance a frontier by assertion.

use serde::{Deserialize, Serialize};

use super::composition_delta::UiCompositionDelta;
use super::composition_identity::UiSurfaceMountManifest;
use super::composition_operation::UiCompositionRequest;
use crate::ids::PresentationId;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum UiCompositionCompletionKind {
    Composition,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct UiCompositionCompletion {
    pub kind: UiCompositionCompletionKind,
    pub schema: u32,
    pub presentation_id: PresentationId,
    pub operation_id: String,
    pub expected_revision: u64,
    pub revision: u64,
    pub expected_next_mount_id: u64,
    pub next_mount_id: u64,
    pub request_digest: String,
    /// Exact IDs derived once from the acknowledged frontier. Absent for
    /// identity-preserving edits, never regenerated by an adapter or retry.
    pub allocated_manifest: Option<UiSurfaceMountManifest>,
    pub allocated_mounts: Option<super::composition_delta::UiCompositionMountAllocation>,
}

impl UiCompositionCompletion {
    pub fn request_digest(request: &UiCompositionRequest) -> Result<String, String> {
        super::seat_digest::seat_payload_digest(&serde_json::json!({
            "domain":"ryeos.ui.composition-request.v1", "request":request,
        }))
        .map_err(|error| error.to_string())
    }

    /// Used by both the producer's staged projection and the prospective
    /// daemon validator. The caller cannot substitute an unrelated delta.
    pub fn from_delta(
        request: &UiCompositionRequest,
        delta: &UiCompositionDelta,
    ) -> Result<Self, String> {
        if delta.composition.id() != &request.presentation_id
            || delta.revision
                != request
                    .expected_revision
                    .checked_add(1)
                    .ok_or("revision exhausted")?
            || delta.next_mount_id < request.expected_next_mount_id
        {
            return Err("composition delta contradicts preparation identity".into());
        }
        let receipt = Self {
            kind: UiCompositionCompletionKind::Composition,
            schema: 1,
            presentation_id: request.presentation_id.clone(),
            operation_id: request.operation_id.clone(),
            expected_revision: request.expected_revision,
            revision: delta.revision,
            expected_next_mount_id: request.expected_next_mount_id,
            next_mount_id: delta.next_mount_id,
            request_digest: Self::request_digest(request)?,
            allocated_manifest: delta.allocated_manifest.clone(),
            allocated_mounts: delta.allocated_mounts.clone(),
        };
        receipt.validate_for(request)?;
        Ok(receipt)
    }

    /// Wire identity and byte-shape only. Exact staged delta equality remains
    /// mandatory before journal append and before local publication.
    pub fn validate_for(&self, request: &UiCompositionRequest) -> Result<(), String> {
        if self.schema != 1
            || self.presentation_id != request.presentation_id
            || self.operation_id != request.operation_id
            || self.expected_revision != request.expected_revision
            || self.revision
                != request
                    .expected_revision
                    .checked_add(1)
                    .ok_or("revision exhausted")?
            || self.expected_next_mount_id != request.expected_next_mount_id
            || self.next_mount_id < self.expected_next_mount_id
            || self.request_digest != Self::request_digest(request)?
        {
            return Err("composition completion contradicts its exact preparation".into());
        }
        if let Some(allocation) = &self.allocated_mounts {
            if self.allocated_manifest.is_some()
                || allocation.allocation_start != self.expected_next_mount_id
                || allocation.next_mount_id != self.next_mount_id
            {
                return Err("in-place allocation contradicts receipt".into());
            }
            return allocation.validate();
        }
        match &self.allocated_manifest {
            None if self.next_mount_id == self.expected_next_mount_id => Ok(()),
            Some(manifest)
                if manifest.presentation_id == self.presentation_id
                    && request.owner.surface_instance_id()
                        == Some(&manifest.surface_instance_id)
                    && manifest.allocation_start == self.expected_next_mount_id
                    && manifest.next_mount_id == self.next_mount_id =>
            {
                manifest.validate()
            }
            _ => Err("composition receipt allocation contradicts its frontier".into()),
        }
    }
}
