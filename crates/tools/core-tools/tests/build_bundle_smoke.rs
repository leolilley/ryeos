//! Smoke tests for the signed build-bundle manifest pipeline.
//!
//! These tests verify the *structure* of a built bundle without
//! re-running the full build pipeline (which requires `cargo build`).
//!
//! Prerequisite: a populated `bundles/directive/.ai/bin/<triple>/`
//! plus CAS objects + refs. Regenerate via:
//!   `ryeos publish bundles/directive --key .dev-keys/PUBLISHER_DEV.pem`

use sha2::Digest;
use std::path::Path;

/// The directive bundle directory relative to workspace root. It owns the
/// directive runtime binary that the structural checks below inspect.
fn bundle_dir() -> std::path::PathBuf {
    workspace_root().join("bundles/directive")
}

/// Every shipped bundle: each directory under `bundles/` that has an `.ai` dir.
fn shipped_bundle_dirs() -> Vec<std::path::PathBuf> {
    let mut dirs: Vec<_> = std::fs::read_dir(workspace_root().join("bundles"))
        .expect("read bundles dir")
        .map(|entry| entry.expect("bundles entry").path())
        .filter(|path| path.join(".ai").is_dir())
        .collect();
    dirs.sort();
    dirs
}

/// The bundles that ship the workflow kinds and their runtimes.
fn workflow_bundle_dirs() -> Vec<std::path::PathBuf> {
    ["knowledge", "directive", "graph"]
        .iter()
        .map(|name| workspace_root().join("bundles").join(name))
        .collect()
}

fn read_signed_manifest_hash(path: &Path) -> String {
    let content = std::fs::read_to_string(path).expect("read signed manifest ref");
    let (signature_line, body) = content
        .split_once('\n')
        .expect("manifest ref must contain signature header and hash body");
    lillux::signature::parse_signature_line(signature_line, "#", None)
        .expect("manifest ref must have a RyeOS signature header");
    let hash_body = body
        .strip_prefix(&format!(
            "{}\n",
            ryeos_engine::executor_resolution::EXECUTOR_MANIFEST_REF_DOMAIN
        ))
        .expect("manifest ref must carry the executor-manifest domain separator");
    let hash = hash_body
        .strip_suffix('\n')
        .expect("manifest ref hash body must have a trailing newline");
    assert_eq!(
        body,
        format!(
            "{}\n{hash}\n",
            ryeos_engine::executor_resolution::EXECUTOR_MANIFEST_REF_DOMAIN
        ),
        "manifest ref body shape"
    );
    hash.to_string()
}

/// Default host triple.
fn host_triple() -> String {
    let output = std::process::Command::new("rustc")
        .args(["-vV"])
        .output()
        .expect("rustc -vV");
    let stdout = String::from_utf8_lossy(&output.stdout);
    stdout
        .lines()
        .find(|l| l.starts_with("host:"))
        .expect("host triple in rustc -vV")
        .strip_prefix("host:")
        .unwrap()
        .trim()
        .to_string()
}

#[test]
fn bundle_binary_exists_and_is_executable() {
    let triple = host_triple();
    let bin_path = bundle_dir()
        .join(".ai/bin")
        .join(&triple)
        .join("ryeos-directive-runtime");

    assert!(
        bin_path.exists(),
        "bundle binary not found at {bin_path:?}. Run: ryeos publish"
    );

    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mode = std::fs::metadata(&bin_path).unwrap().permissions().mode();
        assert_eq!(mode & 0o111, 0o111, "binary should be executable");
    }
}

#[test]
fn bundle_sidecar_exists_and_parsable() {
    let triple = host_triple();
    let sidecar_path = bundle_dir()
        .join(".ai/bin")
        .join(&triple)
        .join("ryeos-directive-runtime.item_source.json");

    assert!(
        sidecar_path.exists(),
        "sidecar not found at {sidecar_path:?}"
    );

    let content = std::fs::read_to_string(&sidecar_path).expect("read sidecar");

    // The sidecar is signed — skip the signature header, parse the JSON body
    let json_start = content
        .find('\n')
        .expect("sidecar should have signature header line followed by JSON");
    let json_str = &content[json_start + 1..];
    let value: serde_json::Value =
        serde_json::from_str(json_str).expect("sidecar JSON body should be valid");

    assert_eq!(
        value["item_ref"],
        format!("bin/{triple}/ryeos-directive-runtime"),
        "item_ref mismatch"
    );
    assert!(
        value.get("content_blob_hash").is_some(),
        "missing content_blob_hash"
    );
    assert!(value.get("mode").is_some(), "missing mode");
    assert_eq!(value["mode"], 493, "mode should be 0o755");
    assert_eq!(
        value.get("signature_info"),
        Some(&serde_json::Value::Null),
        "unsigned ItemSource must carry an explicit null, never a claimed signer fingerprint"
    );
}

#[test]
fn bundle_manifest_ref_exists() {
    let ref_path = bundle_dir().join(".ai/refs/bundles/manifest");

    if !ref_path.exists() {
        // The manifest ref is a build artifact generated by `rebuild-manifest`.
        // It may not exist in all checkouts — skip gracefully rather than fail.
        eprintln!(
            "skipping bundle_manifest_ref_exists: manifest ref not found at {:?}. \
              Run: ryeos publish bundles/directive --key .dev-keys/PUBLISHER_DEV.pem",
            ref_path
        );
        return;
    }

    let hash = read_signed_manifest_hash(&ref_path);

    // SHA-256 hash is 64 hex chars
    assert_eq!(hash.len(), 64, "manifest ref should be 64-char hex hash");
    assert!(
        hash.chars().all(|c| c.is_ascii_hexdigit()),
        "manifest ref should be hex"
    );
}

#[test]
fn bundle_cas_contains_manifest_object() {
    let ref_path = bundle_dir().join(".ai/refs/bundles/manifest");
    if !ref_path.exists() {
        return; // Skip if bundle not built
    }

    let hash = read_signed_manifest_hash(&ref_path);

    let objects_dir = bundle_dir().join(".ai/objects/objects");
    // lillux uses 2+2 shard prefix
    let shard = format!("{}/{}", &hash[..2], &hash[2..4]);
    let object_path = objects_dir.join(&shard).join(format!("{hash}.json"));

    assert!(
        object_path.exists(),
        "manifest object not found at {object_path:?}"
    );

    let content = std::fs::read_to_string(&object_path).expect("read manifest object");
    let value: serde_json::Value =
        serde_json::from_str(&content).expect("manifest object should be valid JSON");

    assert_eq!(value["kind"], "source_manifest");
    assert!(
        value.get("item_source_hashes").is_some(),
        "manifest should have item_source_hashes"
    );
}

#[test]
fn bundle_cas_contains_binary_blob() {
    let ref_path = bundle_dir().join(".ai/refs/bundles/manifest");
    if !ref_path.exists() {
        return; // Skip if bundle not built
    }

    // Load the manifest to get the item_source hash
    let manifest_hash = read_signed_manifest_hash(&ref_path);

    let objects_dir = bundle_dir().join(".ai/objects/objects");
    let shard = format!("{}/{}", &manifest_hash[..2], &manifest_hash[2..4]);
    let manifest_path = objects_dir
        .join(&shard)
        .join(format!("{manifest_hash}.json"));

    let manifest_content = std::fs::read_to_string(&manifest_path).unwrap();
    let manifest: serde_json::Value = serde_json::from_str(&manifest_content).unwrap();

    // Get the item_source_hash for our binary
    let triple = host_triple();
    let item_ref = format!("bin/{triple}/ryeos-directive-runtime");
    let item_source_hash = manifest["item_source_hashes"][&item_ref]
        .as_str()
        .expect("item_source_hash not found in manifest");

    // Load the item_source to get the blob hash
    let is_shard = format!("{}/{}", &item_source_hash[..2], &item_source_hash[2..4]);
    let is_path = objects_dir
        .join(&is_shard)
        .join(format!("{item_source_hash}.json"));
    let is_content = std::fs::read_to_string(&is_path).unwrap();
    let item_source: serde_json::Value = serde_json::from_str(&is_content).unwrap();

    let blob_hash = item_source["content_blob_hash"]
        .as_str()
        .expect("content_blob_hash missing");

    // Verify blob exists
    let blobs_dir = bundle_dir().join(".ai/objects/blobs");
    let blob_shard = format!("{}/{}", &blob_hash[..2], &blob_hash[2..4]);
    let blob_path = blobs_dir.join(&blob_shard).join(blob_hash);

    assert!(blob_path.exists(), "binary blob not found at {blob_path:?}");

    // Verify blob hash matches
    let blob_bytes = std::fs::read(&blob_path).unwrap();
    let computed_hash = format!("{:x}", sha2::Sha256::digest(&blob_bytes));
    assert_eq!(
        computed_hash, blob_hash,
        "blob content hash mismatch (corrupted blob)"
    );
}

#[test]
fn workflow_bundles_have_no_old_tool_descriptors() {
    for bundle in workflow_bundle_dirs() {
        let tools_dir = bundle.join(".ai").join("tools").join("ryeos");
        if !tools_dir.is_dir() {
            continue;
        }

        let mut yaml_files = Vec::new();
        walk_yaml_files(&tools_dir, &mut yaml_files);
        yaml_files.retain(|path| {
            path.strip_prefix(&tools_dir)
                .map(|rel| rel != Path::new("knowledge/compose.yaml"))
                .unwrap_or(true)
        });

        // The workflow bundles ship no legacy Python/HTTP provider or
        // state-graph tool descriptors under tools/ryeos/. Runtime delegation
        // is via runtimes/ pointing at native Rust binaries; model providers
        // are config-driven. The knowledge compose wrapper is intentionally a
        // knowledge-bundle tool because it routes to the knowledge kind/runtime
        // through method dispatch.
        assert!(
            yaml_files.is_empty(),
            "{}'s tools/ryeos/ contains old state-graph/provider \
             tool descriptors; found {:?}",
            bundle.display(),
            yaml_files
        );
    }
}

#[test]
fn no_old_state_graph_executor_ids_in_fixtures() {
    let workspace = workspace_root();
    let fixtures_root = workspace.join("tests/e2e");
    if !fixtures_root.exists() {
        return;
    }

    let mut yaml_files = Vec::new();
    for entry in std::fs::read_dir(&fixtures_root).unwrap() {
        let project_root = entry.unwrap().path();
        let project_ai = project_root.join(".ai");
        if project_ai.is_dir() {
            walk_yaml_files(&project_ai, &mut yaml_files);
        }
    }
    for path in yaml_files {
        let content = std::fs::read_to_string(&path).unwrap();
        assert!(
            !content.contains("ryeos/core/runtimes/state-graph/runtime"),
            "old state-graph executor_id remains in {}",
            path.display()
        );
    }
}

